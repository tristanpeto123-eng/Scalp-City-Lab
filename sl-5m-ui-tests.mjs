import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
const html=readFileSync(new URL('./sl-strategy.html',import.meta.url),'utf8');
assert.match(html,/id="fiveMinuteLab"/);
assert.match(html,/sl-5m\.mjs/);
assert.match(html,/id="fiveChart"/);
assert.match(html,/id="fiveBuild"/);
assert.match(html,/id="fiveOnlineKey"/);
assert.match(html,/id="fiveOnlineLoad"/);
assert.match(html,/id="loopStart"/);
assert.match(html,/id="loopPause"/);
assert.match(html,/id="loopOnce"/);
assert.match(html,/id="vaultOwner"/);
assert.match(html,/id="vaultRepo"/);
assert.match(html,/id="vaultToken"/);
assert.match(html,/id="vaultAuto"/);
assert.match(html,/id="vaultDownload"/);
assert.match(html,/id="vaultRestore"/);
assert.match(html,/sl-model-vault\.mjs/);
assert.match(html,/sl-loop\.mjs/);
assert.match(html,/sl-online-5m\.mjs/);
assert.match(html,/Twelve Data/);
const scripts=[...html.matchAll(/<script\b[^>]*type="module"[^>]*>([\s\S]*?)<\/script>/g)];
assert.equal(scripts.length,1,'SL console has one inline module');
const code=scripts[0][1];
const result=spawnSync(process.execPath,['--input-type=module','--check'],{input:code,encoding:'utf8'});
assert.equal(result.status,0,'SL module syntax: '+result.stderr);
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(x=>x[1]);
assert.equal(new Set(ids).size,ids.length,'no duplicated element IDs');
for(const [,id] of code.matchAll(/\$\('([^']+)'\)/g)){
 assert.ok(ids.includes(id),'UI references an absent element: '+id);
}
assert.match(code,/view=bars\.slice\(from,end\+1\)/,'replay chart draws only revealed bars');
assert.match(code,/predictSL\(/,'neural policy integrated');
assert.match(code,/loadSLOnlineFiveMinute\(/,'online provider loading wired to UI');
assert.match(code,/initializeSLLoop\(/,'SL loop bootstrap is connected');
assert.match(code,/advanceSLLoop\(/,'SL causal loop refresh connected');
assert.match(code,/loopSchedule\(/,'future 5m cycle scheduled');
assert.match(code,/createSLVaultEnvelope\(/,'learned model can be exported as verified checkpoint');
assert.match(code,/writePrivateSLVault\(/,'model vault cloud save wired');
assert.match(code,/readPrivateSLVault\(/,'model vault restore wired');
assert.match(code,/copied!==value/,'local browser saved weights read back');
assert.doesNotMatch(code,/localStorage\.setItem\([^\n]*vaultToken/,'GitHub PAT never written to localStorage');
assert.doesNotMatch(code,/localStorage\.setItem\([^\n]*fiveOnlineKey/,'API key not saved in checkpoint');
assert.doesNotMatch(code,/localStorage\.setItem\([^\n]*fiveOnlineKey/,'never persist API key');
assert.doesNotMatch(code,/fetch\(|WebSocket|sendOrder|placeOrder|tradeAPI/,'offline read-only UI');
console.log('SL 5m UI checks passed: JS syntax, elements, hidden future bars, on-demand provider wired without persistent key, no order route');