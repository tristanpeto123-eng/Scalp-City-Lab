import assert from 'node:assert/strict';
import {initializeTrial,netRiskPlan,queueSignal,processBar,trialReport,TRIAL_RULES} from './trial-50gbp.mjs';
import {measureGoal,wilsonLowerBound} from './performance.mjs';
let checked=0;const t0='2026-10-17T18:00:00Z',t1='2026-10-17T18:15:00Z',t2='2026-10-17T18:30:00Z';
const candle=(t,o,h,l,c,symbol='BTC/USD')=>({t,o,h,l,c,symbol});
let trial=initializeTrial();
assert.equal(trial.balanceGbp,50);checked++;
assert.equal(trial.currency,'GBP_VIRTUAL');checked++;
assert.equal(TRIAL_RULES.rewardToRisk,3);checked++;
const plan=netRiskPlan({balanceGbp:50,entryPrice:100});
assert.ok(plan.plannedRiskGbp<=.5+1e-8);checked++;
assert.ok(Math.abs(plan.plannedRewardGbp-3*plan.plannedRiskGbp)<1e-6);checked++;
assert.ok(plan.notionalGbp<=25);checked++;
assert.equal(plan.plannedNetRR,3);checked++;
const pending=queueSignal(trial,{symbol:'BTC/USD',signalBarStart:t0,candidateId:'candidate-a'});
assert.equal(pending.result,'PENDING_NEXT_CANDLE');checked++;
trial=pending.state;
const noFuture=processBar(trial,candle(t0,100,105,96,103));
assert.equal(noFuture.state.open,null);checked++;
trial=noFuture.state;
const opened=processBar(trial,candle(t1,100,100.5,99.4,100));
assert.equal(opened.result,'OPEN');checked++;
trial=opened.state;assert.equal(trial.open.notionalGbp,plan.notionalGbp);checked++;
const dup=processBar(trial,candle(t1,100,100.5,99.4,100));
assert.equal(dup.result,'DUPLICATE_OR_OUT_OF_ORDER');checked++;
let won=processBar(trial,candle(t2,100,plan.targetPrice+1,99.4,101));
assert.equal(won.result,'TAKE_PROFIT');checked++;
assert.ok(Math.abs(won.closed.netGbp-plan.plannedRewardGbp)<1e-5);checked++;
assert.ok(won.state.balanceGbp>50);checked++;
assert.equal(trialReport(won.state).closedTrades,1);checked++;
assert.equal(trialReport(won.state).status,'INSUFFICIENT_CLOSED_TRADES');checked++;
let lost=initializeTrial();
lost=queueSignal(lost,{symbol:'ETH/USD',signalBarStart:t0,candidateId:'candidate-a'}).state;
const both=processBar(lost,candle(t1,100,plan.targetPrice+3,plan.stopPrice-1,100,'ETH/USD'));
assert.equal(both.result,'STOP');checked++;
assert.equal(both.closed.bothBarriersTouched,true);checked++;
assert.ok(Math.abs(both.closed.netGbp+plan.plannedRiskGbp)<1e-5);checked++;
assert.ok(both.state.balanceGbp<50);checked++;
const avoidInflation=processBar(both.state,candle(t1,100,plan.targetPrice+3,plan.stopPrice-1,100,'ETH/USD'));
assert.equal(avoidInflation.state.closedTrades.length,1);checked++;
let manual=initializeTrial();
assert.throws(()=>queueSignal(manual,{symbol:'DOGE/USD',signalBarStart:t0,candidateId:'x'}),/Invalid/);checked++;
assert.throws(()=>processBar(manual,candle(t1,100,90,110,100)),/Invalid/);checked++;
const winSample=Array.from({length:61},(_,i)=>({id:'v'+i,closedAt:new Date(Date.parse(t0)+i*900000).toISOString(),
 netUsd:i<49?1.5:-.5,cohort:'same',evidence:'VIRTUAL_FORWARD_BAR_SIMULATION',feeBasis:'MODELED_NOT_POSTED'}));
const measured=measureGoal(winSample);
assert.equal(measured.closedTrades,61);checked++;
assert.equal(measured.wins,49);checked++;
assert.equal(measured.observedThresholdMet,true);checked++;
assert.equal(measured.verifiedTargetMet,false);checked++;
assert.equal(measured.status,'PROVISIONAL_COSTS_OR_EVIDENCE');checked++;
assert.ok(wilsonLowerBound(49,61)<.8);checked++;
const less=measureGoal(winSample.slice(0,60));
assert.notEqual(less.status,'TARGET_VERIFIED');checked++;
const invalid=winSample.map((x,i)=>({...x,id:i?x.id:'v1'}));
assert.throws(()=>measureGoal(invalid),/Duplicate/);checked++;
const different=winSample.map((x,i)=>({...x,cohort:i>30?'different':'same'}));
assert.equal(measureGoal(different).status,'MIXED_STRATEGY_COHORT');checked++;
const expired=queueSignal(initializeTrial(),{symbol:'BTC/USD',signalBarStart:t0,candidateId:'candidate-expired'}).state;
const expiredBar=processBar(expired,candle('2026-10-17T19:00:00Z',100,100,99,100));
assert.equal(expiredBar.result,'SIGNAL_EXPIRED');checked++;
assert.equal(expiredBar.state.open,null);checked++;
assert.equal(expiredBar.state.pending,null);checked++;
assert.equal(expiredBar.state.closedTrades.length,0);checked++;
console.log('PASS '+checked+' GBP-50 virtual risk:3R tests, no broker orders');
